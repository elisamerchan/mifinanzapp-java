package com.mifinanzapp.servlets.config;

import com.mifinanzapp.servlets.dao.CategoriaDao;
import jakarta.servlet.ServletContext;
import jakarta.servlet.ServletContextEvent;
import jakarta.servlet.ServletContextListener;
import jakarta.servlet.annotation.WebListener;
import org.h2.jdbcx.JdbcDataSource;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Se ejecuta al arrancar la aplicación: crea la base de datos H2 en memoria,
 * crea la tabla, inserta datos de ejemplo y publica el {@link CategoriaDao} en el contexto.
 * Al ser en memoria, los datos se reinician cada vez que se reinicia Tomcat.
 */
@WebListener
public class InicializadorBaseDatos implements ServletContextListener {

    /** Nombre del atributo del contexto donde queda el DAO para los servlets. */
    public static final String ATRIBUTO_DAO = "categoriaDao";

    private static final String URL_BASE_DATOS =
            "jdbc:h2:mem:mifinanzapp;DB_CLOSE_DELAY=-1;MODE=PostgreSQL";

    private static final String SQL_CREAR_TABLA = """
            CREATE TABLE IF NOT EXISTS categorias (
                id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre VARCHAR(60) NOT NULL,
                tipo   VARCHAR(10) NOT NULL CHECK (tipo IN ('INGRESO', 'GASTO'))
            )
            """;

    private static final String SQL_DATOS_EJEMPLO = """
            INSERT INTO categorias (nombre, tipo) VALUES
                ('Salario', 'INGRESO'),
                ('Ventas', 'INGRESO'),
                ('Alimentación', 'GASTO'),
                ('Transporte', 'GASTO')
            """;

    @Override
    public void contextInitialized(ServletContextEvent evento) {
        DataSource dataSource = crearDataSource();
        crearEsquema(dataSource);

        ServletContext contexto = evento.getServletContext();
        contexto.setAttribute(ATRIBUTO_DAO, new CategoriaDao(dataSource));
    }

    /** Crea un DataSource H2 en memoria con la URL indicada. Útil también para las pruebas. */
    public static DataSource crearDataSource(String url) {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL(url);
        dataSource.setUser("sa");
        dataSource.setPassword("");
        return dataSource;
    }

    private static DataSource crearDataSource() {
        return crearDataSource(URL_BASE_DATOS);
    }

    /**
     * Crea la tabla y, si está vacía, inserta los datos de ejemplo.
     * Es idempotente: se puede llamar varias veces sin duplicar datos.
     */
    public static void crearEsquema(DataSource dataSource) {
        try (Connection conexion = dataSource.getConnection();
             Statement sentencia = conexion.createStatement()) {
            sentencia.execute(SQL_CREAR_TABLA);
            try (var resultado = sentencia.executeQuery("SELECT COUNT(*) FROM categorias")) {
                resultado.next();
                if (resultado.getLong(1) == 0) {
                    sentencia.execute(SQL_DATOS_EJEMPLO);
                }
            }
        } catch (SQLException e) {
            throw new IllegalStateException("No se pudo crear el esquema de la base de datos", e);
        }
    }
}
